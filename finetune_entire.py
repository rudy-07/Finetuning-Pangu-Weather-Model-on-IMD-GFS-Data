class NetCDFDataset(data.Dataset):
    """Dataset class for the era5 upper and surface variables."""
    def __init__(self, nc_path, data_transform=None, seed=1234, training=True, validation=False, startDate='20150101', endDate='20150102', freq='H', horizon=24):
        self.horizon = horizon
        self.nc_path = nc_path
        self.training = training
        self.validation = validation
        self.data_transform = data_transform
        # Per-worker file cache: avoids re-opening the same NetCDF file
        # repeatedly within one DataLoader worker process.
        self._nc_cache = {}
        
        pd_freq = freq.upper()
        if training or validation:
            self.keys = list(pd.date_range(start=startDate, end=endDate, freq=pd_freq))
        else:
            self.keys = list(pd.date_range(start=startDate, end=endDate, freq=pd_freq))

        freq_digits = ''.join(filter(str.isdigit, freq))
        freq_int = int(freq_digits) if freq_digits else 1
        if horizon % freq_int != 0:
            raise ValueError(f"Horizon ({horizon}h) must be divisible by frequency ({freq}).")
        horizon_steps = horizon // freq_int
        self.length = len(self.keys) - horizon_steps
        if self.length <= 0:
            raise ValueError(f"Dataset length is non-positive ({self.length}). Check date range and horizon.")
        print(f"{'Train' if training else 'Val/Test'} dataset keys: {len(self.keys)}, Length: {self.length}")
        random.seed(seed)

    def _candidate_paths(self, kind, dt):
        if kind == 'surface':
            prefixes = ['surface']
            subdir = 'surface'
        elif kind == 'upper':
            prefixes = ['upper_air', 'upper']
            subdir = 'upper'
        else:
            raise ValueError(f"Unknown kind: {kind}")

        day_str = datetime.strftime(dt, '%Y_%m_%d')
        month_str = datetime.strftime(dt, '%Y_%m')
        day_compact = datetime.strftime(dt, '%Y%m%d')
        month_compact = datetime.strftime(dt, '%Y%m')
        day_dash = datetime.strftime(dt, '%Y-%m-%d')
        month_dash = datetime.strftime(dt, '%Y-%m')
        base_dir = os.path.join(self.nc_path, subdir)
        search_dirs = [
            base_dir,
            self.nc_path,
            os.path.join(base_dir, datetime.strftime(dt, '%Y')),
            os.path.join(base_dir, datetime.strftime(dt, '%Y'), datetime.strftime(dt, '%m')),
            os.path.join(base_dir, month_compact),
        ]

        patterns = []
        for prefix in prefixes:
            patterns.extend([
                f'{prefix}_{day_str}.nc',
                f'{prefix}_{month_str}.nc',
                f'{prefix}_{day_compact}.nc',
                f'{prefix}_{month_compact}.nc',
                f'{prefix}_{day_dash}.nc',
                f'{prefix}_{month_dash}.nc',
            ])
        patterns.extend([
            f'{day_str}.nc',
            f'{month_str}.nc',
            f'{day_compact}.nc',
            f'{month_compact}.nc',
            f'{day_dash}.nc',
            f'{month_dash}.nc',
        ])

        return [os.path.join(directory, pattern) for directory in search_dirs for pattern in patterns]

    def _open_nc(self, kind, dt):
        """
        Open a NetCDF file, normalise its time coordinate, and return the
        open Dataset.  Results are cached by (kind, date-string) so that the
        same file is never opened more than once per worker process.
        """
        cache_key = (kind, dt.strftime('%Y%m%d'))
        if cache_key in self._nc_cache:
            return self._nc_cache[cache_key]

        # Try daily then monthly naming to support both layouts.
        for path in self._candidate_paths(kind, dt):
            if os.path.exists(path):
                ds = xr.open_dataset(path, decode_timedelta=False)
                # Normalise time coordinate so .isel(time=0) always works.
                # Case 1: named 'valid_time' instead of 'time'
                if 'valid_time' in ds.variables and 'time' not in ds.variables:
                    ds = ds.rename({'valid_time': 'time'})
                # Case 2: 'time' is a dimension but not yet an indexed coordinate
                if 'time' in ds.dims and 'time' not in ds.coords:
                    if 'time' in ds.variables:
                        ds = ds.assign_coords(time=ds['time'])
                    elif 'valid_time' in ds.variables:
                        ds = ds.assign_coords(time=ds['valid_time']).drop_vars('valid_time')
                    else:
                        # 'time' is a bare integer dimension with no coordinate
                        # variable at all (2026 surface files written without
                        # encoding datetime info). Reconstruct from dt.
                        correct_ts = np.array(
                            [np.datetime64(dt.strftime('%Y-%m-%dT%H:%M:%S'), 'ns')]
                        )
                        ds = ds.assign_coords(time=('time', correct_ts))
                # Case 3: both 'time' and 'valid_time' present – drop the redundant one
                if 'time' in ds.coords and 'valid_time' in ds.coords:
                    ds = ds.drop_vars('valid_time')
                # Case 4: 'time' coord exists but has integer dtype, not datetime64
                # (safety net: time variable present but not encoded as datetime)
                if 'time' in ds.coords and not np.issubdtype(ds['time'].dtype, np.datetime64):
                    correct_ts = np.array(
                        [np.datetime64(dt.strftime('%Y-%m-%dT%H:%M:%S'), 'ns')]
                    )
                    ds = ds.assign_coords(time=('time', correct_ts))
                self._nc_cache[cache_key] = ds
                return ds
        tried = ", ".join(self._candidate_paths(kind, dt))
        raise FileNotFoundError(f"No {kind} NetCDF file found for {dt:%Y-%m-%d}. Tried: {tried}")

    def __getstate__(self):
        """Don't pickle cached open datasets across multiprocessing workers."""
        state = self.__dict__.copy()
        state['_nc_cache'] = {}
        return state
    def nctonumpy(self, dataset_upper, dataset_surface):
        # Stack all upper-air variables in one shot — fewer .values calls
        # means fewer NetCDF decompressions and fewer intermediate arrays.
        upper = np.stack(
            [dataset_upper[v].values.astype(np.float32)
             for v in ('z', 'q', 't', 'u', 'v')],
            axis=0
        )  # (5, level, lat, lon)
        upper = upper[:, ::-1, :, :].copy()  # levels in descending order

        surface = np.stack(
            [dataset_surface[v].values.astype(np.float32)
             for v in ('msl', 'u10', 'v10', 't2m')],
            axis=0
        )  # (4, lat, lon)
        return upper, surface

    def LoadData(self, key):
        start_time = key
        start_date_str = datetime.strftime(key, '%Y_%m_%d')
        end_time = key + timedelta(hours=self.horizon)
        end_date_str = datetime.strftime(end_time, '%Y_%m_%d')

        # Open all four datasets (cached after first access in this worker)
        input_surface_dataset  = self._open_nc('surface', start_time)
        input_upper_dataset    = self._open_nc('upper',   start_time)
        target_surface_dataset = self._open_nc('surface', end_time)
        target_upper_dataset   = self._open_nc('upper',   end_time)

        # Each daily file has exactly 1 timestep — use positional selection
        # (.isel) which is O(1), rather than .sel(method='nearest') which
        # scans the coordinate array.
        def _sel_time(ds, dt):
            if 'expver' in ds:
                return ds.sel(expver=5).isel(time=0)
            return ds.isel(time=0)

        inp_surf   = _sel_time(input_surface_dataset,  start_time)
        inp_upper  = _sel_time(input_upper_dataset,    start_time)
        tgt_surf   = _sel_time(target_surface_dataset, end_time)
        tgt_upper  = _sel_time(target_upper_dataset,   end_time)

        inp,    inp_surface = self.nctonumpy(inp_upper,  inp_surf)
        target, tgt_surface = self.nctonumpy(tgt_upper,  tgt_surf)
        return inp, inp_surface, target, tgt_surface, (start_date_str, end_date_str)

    def __getitem__(self, index):
        iii = self.keys[index]
        input, input_surface, target, target_surface, periods = self.LoadData(iii)
        if self.training and self.data_transform is not None:
            input = self.data_transform(input)
            input_surface = self.data_transform(input_surface)
        return input, input_surface, target, target_surface, periods

    def __len__(self):
        return self.length

