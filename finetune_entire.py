@torch.jit.script
def lat(j: torch.Tensor, num_lat: int) -> torch.Tensor:
    return 90. - j * 180./float(num_lat-1)

@torch.jit.script
def latitude_weighting_factor_torch(j: torch.Tensor, num_lat: int, s: torch.Tensor) -> torch.Tensor:
    return num_lat * torch.cos(3.1416/180. * lat(j, num_lat))/s

@torch.jit.script
def weighted_rmse_torch_channels(pred: torch.Tensor, target: torch.Tensor, mask: Optional[torch.Tensor] = None) -> torch.Tensor:
    num_lat = pred.shape[-2]
    lat_t = torch.arange(start=0, end=num_lat, device=pred.device)
    s = torch.sum(torch.cos(3.1416/180. * lat(lat_t, num_lat)))

    if pred.dim() == 3:
        weight = torch.reshape(latitude_weighting_factor_torch(lat_t, num_lat, s), (1, -1, 1))
    else:
        weight = torch.reshape(latitude_weighting_factor_torch(lat_t, num_lat, s), (1, 1, -1, 1))

    if mask is not None:
        mask = mask.to(pred.device)
        if pred.dim() == 3:
            mask = mask.unsqueeze(0)
        else:
            mask = mask.unsqueeze(0).unsqueeze(0)
        valid_weights = (weight * mask).sum(dim=(-1, -2))
        squared_error = (pred - target)**2
        weighted_masked_error = weight * mask * squared_error
        result = torch.sqrt(weighted_masked_error.sum(dim=(-1, -2)) / torch.clamp(valid_weights, min=1.0e-12))
    else:
        result = torch.sqrt(torch.mean(weight * (pred - target)**2., dim=(-1, -2)))
    return result

@torch.jit.script
def weighted_acc_torch_channels(pred: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
    num_lat = pred.shape[-2]
    lat_t = torch.arange(start=0, end=num_lat, device=pred.device)
    s = torch.sum(torch.cos(3.1416/180. * lat(lat_t, num_lat)))
    if pred.dim() == 3:
        weight = torch.reshape(latitude_weighting_factor_torch(lat_t, num_lat, s), (1, -1, 1))
    else:
        weight = torch.reshape(latitude_weighting_factor_torch(lat_t, num_lat, s), (1, 1, -1, 1))
    
    numerator = torch.sum(weight * pred * target, dim=(-1, -2))
    denominator = torch.sqrt(torch.sum(weight * pred * pred, dim=(-1, -2)) * torch.sum(weight * target * target, dim=(-1, -2)))
    return numerator / torch.clamp(denominator, min=1.0e-12)

