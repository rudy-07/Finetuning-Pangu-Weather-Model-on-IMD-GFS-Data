def unwrap_model(model):
    return model.module if hasattr(model, 'module') else model

def strip_module_prefix(state_dict):
    return {k.replace('module.', '', 1) if k.startswith('module.') else k: v
            for k, v in state_dict.items()}

def load_model_state(model, checkpoint, strict=True):
    if isinstance(checkpoint, nn.Module):
        state_dict = checkpoint.state_dict()
    else:
        state_dict = checkpoint['model'] if isinstance(checkpoint, dict) and 'model' in checkpoint else checkpoint
    if not hasattr(state_dict, 'items'):
        raise TypeError('Checkpoint must be a state_dict, a dict containing "model", or an nn.Module.')
    unwrap_model(model).load_state_dict(strip_module_prefix(state_dict), strict=strict)

def masked_mean(values, mask):
    mask = mask.to(device=values.device, dtype=values.dtype)
    while mask.dim() < values.dim():
        mask = mask.unsqueeze(0)
    mask = mask.expand_as(values)
    denom = mask.sum().clamp_min(1.0)
    return (values * mask).sum() / denom

def current_learning_rate(optimizer):
    if hasattr(optimizer, 'param_groups') and optimizer.param_groups:
        return optimizer.param_groups[0]['lr']
    inner_optimizer = getattr(optimizer, 'optimizer', None)
    if inner_optimizer is not None and hasattr(inner_optimizer, 'param_groups') and inner_optimizer.param_groups:
        return inner_optimizer.param_groups[0]['lr']
    return 0.0

