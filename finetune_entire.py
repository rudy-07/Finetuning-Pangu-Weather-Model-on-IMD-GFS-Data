class PatchEmbedding_pretrain(nn.Module):
    def __init__(self, patch_size, dim):
        super(PatchEmbedding_pretrain, self).__init__()
        self.conv = nn.Conv1d(in_channels=192, out_channels=dim, kernel_size=1, stride=1)
        self.conv_surface = nn.Conv1d(in_channels=112, out_channels=dim, kernel_size=1, stride=1)
        self.window_size = (2, 6, 12)

    def check_image_size_2d(self, x):
        _, _, h, w = x.size()
        mod_pad_w = (self.window_size[2] - w % self.window_size[2]) % self.window_size[2]
        x = F.pad(x, (0, mod_pad_w, 0, 3), 'constant')
        return x

    def check_image_size_3d(self, x):
        _, _, d, h, w = x.size()
        x = F.pad(x, (0, 0, 0, 3, 0, 1), 'constant')
        return x

    def forward(self, input, input_surface, statistics, maps, const_h):
        self.surface_mean, self.surface_std, self.upper_mean, self.upper_std = statistics[0], statistics[1], statistics[2], statistics[3]
        self.constant_masks = maps

        input_surface = input_surface.reshape(input_surface.shape[0], input_surface.shape[1], 1, input_surface.shape[-2], input_surface.shape[-1])
        input_surface = torch.permute(input_surface, (0, 2, 3, 4, 1))
        input_surface = (input_surface - self.surface_mean) / self.surface_std
        input_surface = torch.permute(input_surface, (0, 4, 1, 2, 3))
        input_surface = input_surface.view(input_surface.shape[0], input_surface.shape[1], input_surface.shape[-2], input_surface.shape[-1])
        input_surface = self.check_image_size_2d(input_surface)
        batch_size = input_surface.shape[0]
        input_surface = torch.cat((input_surface, self.constant_masks.expand(batch_size, -1, -1, -1)), dim=1)
        input_surface = input_surface.view(input_surface.shape[0], input_surface.shape[1], input_surface.shape[-2] // 4, 4, input_surface.shape[-1] // 4, 4)
        input_surface = torch.permute(input_surface, (0, 1, 3, 5, 2, 4))
        input_surface = input_surface.reshape(input_surface.shape[0], input_surface.shape[1] * input_surface.shape[2] * input_surface.shape[3], -1)
        input_surface = self.conv_surface(input_surface)
        input_surface = input_surface.view(input_surface.shape[0], input_surface.shape[1], 1, 181, 360)

        input = input.reshape(input.shape[0], input.shape[1], 1, input.shape[2], input.shape[-2], input.shape[-1])
        input = torch.permute(input, (0, 2, 3, 4, 5, 1))
        input = torch.flip(input, [2])
        input = (input - self.upper_mean) / self.upper_std
        input = torch.permute(input, (0, 5, 1, 2, 3, 4))
        input = torch.flip(input, [3])
        input = torch.cat((input, const_h.expand(batch_size, -1, -1, -1, -1, -1)), dim=1)
        input = input.reshape(input.shape[0], input.shape[1], input.shape[3], input.shape[-2], input.shape[-1])
        input = self.check_image_size_3d(input)
        input = input.reshape(input.shape[0], input.shape[1], input.shape[2] // 2, 2, input.shape[-2] // 4, 4, input.shape[-1] // 4, 4)
        input = input.permute(0, 1, 3, 5, 7, 2, 4, 6)
        input = input.reshape(input.shape[0], input.shape[1] * input.shape[2] * input.shape[3] * input.shape[4], -1)
        input = self.conv(input)
        input = input.view(input.shape[0], input.shape[1], 7, 181, 360)

        x = torch.cat((input_surface, input), dim=2)
        x = x.view(x.shape[0], x.shape[1], -1)
        x = torch.permute(x, (0, 2, 1))
        return x

class Mlp(nn.Module):
    def __init__(self, dim, dropout_rate):
        super().__init__()
        self.linear1 = nn.Linear(dim, dim * 4)
        self.linear2 = nn.Linear(dim * 4, dim)
        self.activation = nn.GELU()
        self.drop = nn.Dropout(dropout_rate)

    def forward(self, x):
        x = self.linear1(x)
        x = self.activation(x)
        x = self.drop(x)
        x = self.linear2(x)
        x = self.drop(x)
        return x

class EarthAttention3D(nn.Module):
    def __init__(self, dim, heads, dropout_rate, window_size, device):
        super(EarthAttention3D, self).__init__()
        self.device = device
        self.linear1 = nn.Linear(dim, dim*3, bias=True)
        self.linear2 = nn.Linear(dim, dim)
        self.softmax = nn.Softmax(dim=-1)
        self.dropout = nn.Dropout(dropout_rate)
        self.head_number = heads
        self.dim = dim
        self.scale = (dim//heads)**-0.5
        self.window_size = window_size
        if self.dim == 192: input_shape = [8, 186]
        elif self.dim == 384: input_shape = [8, 96]
        self.type_of_windows = (input_shape[0]//window_size[0])*(input_shape[1]//window_size[1])
        self.earth_specific_bias = torch.zeros(1, self.type_of_windows, heads,
                                               window_size[0] * window_size[1] * window_size[2],
                                               window_size[0] * window_size[1] * window_size[2]).to(self.device)
        self.earth_specific_bias = nn.Parameter(self.earth_specific_bias)
        trunc_normal_(self.earth_specific_bias, std=0.02)
        self._construct_index()

    def _construct_index(self):
        coords_zi = torch.arange(self.window_size[0]).to(self.device)
        coords_zj = -torch.arange(self.window_size[0]).to(self.device)*self.window_size[0]
        coords_hi = torch.arange(self.window_size[1]).to(self.device)
        coords_hj = -torch.arange(self.window_size[1]).to(self.device)*self.window_size[1]
        coords_w = torch.arange(self.window_size[2]).to(self.device)
        coords_1 = torch.stack(torch.meshgrid([coords_zi, coords_hi, coords_w], indexing='ij'))
        coords_2 = torch.stack(torch.meshgrid([coords_zj, coords_hj, coords_w], indexing='ij'))
        coords_flatten_1 = torch.flatten(coords_1, start_dim=1)
        coords_flatten_2 = torch.flatten(coords_2, start_dim=1)
        coords = coords_flatten_1[:, :, None] - coords_flatten_2[:, None, :]
        coords = torch.permute(coords, (1, 2, 0))
        coords[:, :, 2] += self.window_size[2] - 1
        coords[:, :, 1] *= 2 * self.window_size[2] - 1
        coords[:, :, 0] *= (2 * self.window_size[2] - 1) * self.window_size[1]*self.window_size[1]
        self.position_index = torch.sum(coords, dim=-1)
        self.position_index = torch.flatten(self.position_index)

    def forward(self, x, mask):
        original_shape = x.shape
        x = self.linear1(x)
        qkv = torch.reshape(x, shape=(x.shape[0], x.shape[1], x.shape[2], 3, self.head_number, self.dim // self.head_number))
        qkv = torch.permute(qkv, (3, 0, 1, 4, 2, 5))
        query, key, value = qkv[0], qkv[1], qkv[2]
        query = query * self.scale
        attention = (query @ key.transpose(-2, -1))
        EarthSpecificBias = self.earth_specific_bias
        attention = attention + EarthSpecificBias
        if mask is not None:
            nW = mask.shape[0]
            B = attention.shape[0] // nW
            attention = attention.view(B, nW, self.type_of_windows, self.head_number, 
                                       self.window_size[0]*self.window_size[1]*self.window_size[2], 
                                       self.window_size[0]*self.window_size[1]*self.window_size[2]) + mask.unsqueeze(2).unsqueeze(0)
            attention = attention.reshape(B*nW, self.type_of_windows, self.head_number,
                                          self.window_size[0]*self.window_size[1]*self.window_size[2], 
                                          self.window_size[0]*self.window_size[1]*self.window_size[2])
        attention = self.softmax(attention)
        attention = self.dropout(attention)
        x = attention @ value
        x = torch.permute(x, (0, 1, 3, 2, 4))
        x = torch.reshape(x, shape=original_shape)
        x = self.linear2(x)
        x = self.dropout(x)
        return x

class EarthSpecificBlock(nn.Module):
    def __init__(self, dim, drop_path_ratio, heads, device):
        super(EarthSpecificBlock, self).__init__()
        self.device = device
        self.window_size = (2, 6, 12)
        self.drop_path = DropPath(drop_path_ratio) if drop_path_ratio > 0. else nn.Identity()
        self.norm1 = nn.LayerNorm(dim)
        self.norm2 = nn.LayerNorm(dim)
        self.linear = Mlp(dim, 0)
        self.attention = EarthAttention3D(dim, heads, 0, self.window_size, device=self.device)
        self.padding_front, self.padding_back = 0, 5
        if dim == 192: input_shape = [8, 186]
        elif dim == 384: input_shape = [8, 96]
        self.type_of_windows = (input_shape[0]//self.window_size[0])*(input_shape[1]//self.window_size[1])

    def gen_mask(self, x):
        img_mask = torch.zeros((1, x.shape[1], x.shape[2], x.shape[3], 1)).to(self.device)
        mB, mZ, mH, mW, mC = img_mask.shape
        cnt = 0
        z_slices = (slice(0, -self.window_size[0]), slice(-self.window_size[0], -self.window_size[0] // 2), slice(-self.window_size[0] // 2, None))
        h_slices = (slice(0, -self.window_size[1]), slice(self.window_size[1], -self.window_size[1] // 2), slice(-self.window_size[1] // 2, None))
        for z in z_slices:
            for h in h_slices:
                img_mask[:, z, h, :, :] = cnt
                cnt += 1
        img_mask = img_mask.reshape(1, mZ // self.window_size[0], self.window_size[0], mH // self.window_size[1],
                                    self.window_size[1], mW // self.window_size[2], self.window_size[2], 1)
        img_mask = torch.permute(img_mask, (0, 5, 1, 3, 2, 4, 6, 7))
        mask_windows = img_mask.reshape(-1, self.type_of_windows, self.window_size[0], self.window_size[1], self.window_size[2], 1)
        mask_windows = mask_windows.view(-1, self.type_of_windows, self.window_size[0] * self.window_size[1] * self.window_size[2])
        attn_mask = mask_windows.unsqueeze(2) - mask_windows.unsqueeze(3)
        attn_mask = attn_mask.masked_fill(attn_mask != 0, float(-100.0)).masked_fill(attn_mask == 0, float(0.0))
        return attn_mask

    def forward(self, x, Z, H, W, roll):
        shortcut = x
        x = x.view(x.shape[0], Z, H, W, x.shape[2])
        x = F.pad(x, (0, 0, 0, 0, self.padding_front, self.padding_back), 'constant')
        ori_shape = x.shape
        if roll:
            x = torch.roll(x, shifts=[-self.window_size[0]//2, -self.window_size[1]//2, -self.window_size[2]//2], dims=(1, 2, 3))
            mask = self.gen_mask(x)
        else:
            mask = None

        x_window = x.view(x.shape[0], x.shape[1]//self.window_size[0], self.window_size[0], x.shape[2] // self.window_size[1], self.window_size[1], x.shape[3] // self.window_size[2], self.window_size[2], x.shape[-1])
        x_window = torch.permute(x_window, (0, 5, 1, 3, 2, 4, 6, 7))
        x_window = x_window.reshape(x_window.shape[0] * x_window.shape[1], x_window.shape[2]*x_window.shape[3], x_window.shape[4], x_window.shape[5], x_window.shape[6], x_window.shape[7])
        x_window = x_window.contiguous().view(x_window.shape[0], x_window.shape[1], self.window_size[0]*self.window_size[1]*self.window_size[2], x_window.shape[-1])
        attn_windows = self.attention(x_window, mask)
        x_shifted = attn_windows.view(1, attn_windows.shape[0], Z // self.window_size[0], H // self.window_size[1] + 1, self.window_size[0], self.window_size[1], self.window_size[2], -1)
        x_shifted = torch.permute(x_shifted, (0, 2, 4, 3, 5, 1, 6, 7))
        x_shifted = x_shifted.contiguous().view(ori_shape)
        if roll:
            x = torch.roll(x_shifted, shifts=[self.window_size[0]//2, self.window_size[1]//2, self.window_size[2]//2], dims=(1, 2, 3))
        else:
            x = x_shifted
        depth_slice = slice(self.padding_front, x.shape[2] - self.padding_back)
        x = x[:, :, depth_slice, :, :]
        x = x.contiguous().view(x.shape[0], x.shape[1]*x.shape[2]*x.shape[3], x.shape[4])
        x = shortcut + self.drop_path(self.norm1(x))
        x = x + self.drop_path(self.norm2(self.linear(x)))
        return x

class EarthSpecificLayer(nn.Module):
    def __init__(self, depth, dim, drop_path_ratio_list, heads, use_checkpoint, device):
        super(EarthSpecificLayer, self).__init__()
        self.device = device
        self.depth = depth
        block_list = OrderedDict()
        for i_layer in range(depth):
            block_list['EarthSpecificBlock{}'.format(i_layer)] = EarthSpecificBlock(dim, drop_path_ratio_list[i_layer], heads, device=self.device)
        self.blocks = nn.Sequential(block_list)
        self.use_checkpoint = use_checkpoint

    def forward(self, x, Z, H, W):
        i = -1
        for blk in self.blocks:
            i += 1
            if self.use_checkpoint:
                if i % 2 == 0: x = checkpoint.checkpoint(blk, x, Z, H, W, False, use_reentrant=False)
                else: x = checkpoint.checkpoint(blk, x, Z, H, W, True, use_reentrant=False)
            else:
                if i % 2 == 0: x = blk(x, Z, H, W, roll=False)
                else: x = blk(x, Z, H, W, roll=True)
        return x

class DownSample(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.linear = nn.Linear(in_features=4*dim, out_features=2*dim, bias=False)
        self.norm = nn.LayerNorm(4*dim)

    def forward(self, x, Z, H, W):
        x = x.view(x.shape[0], Z, H, W, x.shape[-1])
        x = F.pad(x, (0, 0, 0, 0, 0, 1), 'constant')
        Z, H, W = x.shape[1], x.shape[2], x.shape[3]
        x = x.view(x.shape[0], Z, H//2, 2, W//2, 2, x.shape[-1])
        x = torch.permute(x, (0, 1, 2, 4, 3, 5, 6))
        x = x.reshape(x.shape[0], Z*(H//2)*(W//2), 4 * x.shape[-1])
        x = self.norm(x)
        x = self.linear(x)
        return x

