def get_all_variables(output_surface, target_surface, output, target):
    """
    Extracts all individual variables from the Surface and Upper-Air tensors.
    
    Surface Channels (4):  0=MSLP, 1=U10, 2=V10, 3=T2M
    Upper Channels (5):    0=Z, 1=Q, 2=T, 3=U, 4=V
    """
    
    # --- SURFACE VARIABLES ---
    # Shape: (Batch, Channel, Lat, Lon)
    
    # 1. MSLP (Mean Sea Level Pressure) - Channel 0
    pred_mslp = output_surface[:, 0, :, :]
    true_mslp = target_surface[:, 0, :, :]
    
    # 2. U10 (10m U-Wind) - Channel 1
    pred_u10 = output_surface[:, 1, :, :]
    true_u10 = target_surface[:, 1, :, :]
    
    # 3. V10 (10m V-Wind) - Channel 2
    pred_v10 = output_surface[:, 2, :, :]
    true_v10 = target_surface[:, 2, :, :]
    
    # 4. T2M (2m Temperature) - Channel 3
    pred_t2m = output_surface[:, 3, :, :]
    true_t2m = target_surface[:, 3, :, :]
    
    # --- UPPER AIR VARIABLES ---
    # Shape: (Batch, Channel, Depth, Lat, Lon)
    
    # 5. Z (Geopotential) - Channel 0
    pred_z = output[:, 0, :, :, :]
    true_z = target[:, 0, :, :, :]
    
    # 6. Q (Specific Humidity) - Channel 1
    pred_q = output[:, 1, :, :, :]
    true_q = target[:, 1, :, :, :]
    
    # 7. T (Temperature) - Channel 2
    pred_t = output[:, 2, :, :, :]
    true_t = target[:, 2, :, :, :]
    
    # 8. U (U-Wind) - Channel 3
    pred_u = output[:, 3, :, :, :]
    true_u = target[:, 3, :, :, :]
    
    # 9. V (V-Wind) - Channel 4
    pred_v = output[:, 4, :, :, :]
    true_v = target[:, 4, :, :, :]
    
    # Optional: Calculate Wind Speeds as well (Derived)
    pred_ws_10 = torch.sqrt(pred_u10**2 + pred_v10**2)
    true_ws_10 = torch.sqrt(true_u10**2 + true_v10**2)
    pred_ws_upper = torch.sqrt(pred_u**2 + pred_v**2)
    true_ws_upper = torch.sqrt(true_u**2 + true_v**2)

    # Return a dictionary for easy access
    return {
        # Surface
        "mslp": (pred_mslp, true_mslp),
        "u10":  (pred_u10, true_u10),
        "v10":  (pred_v10, true_v10),
        "t2m":  (pred_t2m, true_t2m),
        "ws10": (pred_ws_10, true_ws_10),
        
        # Upper Air
        "z": (pred_z, true_z),
        "q": (pred_q, true_q),
        "t": (pred_t, true_t),
        "u": (pred_u, true_u),
        "v": (pred_v, true_v),
        "ws_upper": (pred_ws_upper, true_ws_upper)
    }

def train(model, train_loader, val_loader, optimizer, lr_scheduler, res_path, device, writer, logger, start_epoch,
        rank=0, visualize=False, only_use_wind_speed_loss=False, use_custom_mask=False, use_deepspeed=False,
        train_sampler=None):
    criterion = nn.L1Loss(reduction='none')
    epochs = cfg.PG.TRAIN.EPOCHS
    accumulation_steps = max(1, int(cfg.PG.TRAIN.ACCUMULATION_STEPS))
    if len(train_loader) == 0:
        raise ValueError('Training DataLoader is empty. Check dataset dates, batch size, and drop_last settings.')
    if len(val_loader) == 0:
        raise ValueError('Validation DataLoader is empty. Check validation dates and batch size.')
    best_loss = float('inf')
    epochs_since_last_improvement = 0

    aux_constants = loadAllConstants(device=device)
    upper_weights, surface_weights, upper_loss_weight, surface_loss_weight = aux_constants['variable_weights']

    mask = None
    if use_custom_mask:
        mask = aux_constants['custom_mask']
        if mask is None:
            raise ValueError('Custom mask requested but aux_data/custom_mask.npy was not found.')
        mask_float = (mask != 0).float()
        valid_points = mask_float.sum()
        if valid_points.item() <= 0:
            raise ValueError('Custom mask requested but aux_data/custom_mask.npy has no valid points.')

    for i in range(start_epoch, epochs + 1):
        should_stop = False
        if train_sampler is not None:
            train_sampler.set_epoch(i)
        model.train()
        epoch_loss = 0.0
        epoch_start = time.time()
        total_train_batches = len(train_loader)

        for iter_num, train_data in enumerate(tqdm(train_loader, desc=f'Training epoch {i} rank {rank}')):
            if not use_deepspeed and iter_num % accumulation_steps == 0:
                optimizer.zero_grad(set_to_none=True)

            input, input_surface, target, target_surface, periods = train_data
            input, input_surface, target, target_surface = input.to(device), input_surface.to(device), target.to(device), target_surface.to(device)

            output, output_surface = model(input, input_surface, aux_constants['weather_statistics'],
                                           aux_constants['constant_maps'], aux_constants['const_h'])

            target, target_surface = normData(target, target_surface, aux_constants['weather_statistics_last'])
            
            # --- UPDATED LOSS LOGIC ---
            # Extract all variables for flexible loss calculation
            # finetune
            vars = get_all_variables(output_surface, target_surface, output, target)
            
            if only_use_wind_speed_loss:
                # Use the pre-calculated wind speeds from our new dictionary
                # ws10 is tuple (pred, true)
                surface_wind_speed_loss = criterion(vars['ws10'][0], vars['ws10'][1])
                wind_speed_loss = criterion(vars['ws_upper'][0], vars['ws_upper'][1])
                
                if use_custom_mask:
                    surface_wind_speed_loss = masked_mean(surface_wind_speed_loss, mask_float)
                    wind_speed_loss = masked_mean(wind_speed_loss, mask_float)
                    loss = surface_wind_speed_loss + wind_speed_loss
                else:
                    loss = torch.mean(surface_wind_speed_loss) + torch.mean(wind_speed_loss)
            else:
                # Standard Loss Calculation (Weighted Sum)
                loss_surface = criterion(output_surface, target_surface)
                loss_upper = criterion(output, target)
                
                if use_custom_mask:
                    weighted_surface_loss = masked_mean(loss_surface * surface_weights, mask_float)
                    weighted_upper_loss = masked_mean(loss_upper * upper_weights, mask_float)
                else:
                    weighted_surface_loss = torch.mean(loss_surface * surface_weights)
                    weighted_upper_loss = torch.mean(loss_upper * upper_weights)
                loss = weighted_upper_loss * upper_loss_weight + weighted_surface_loss * surface_loss_weight

            if use_deepspeed:
                model.backward(loss)
                model.step()
            else:
                window_start = (iter_num // accumulation_steps) * accumulation_steps
                window_size = min(accumulation_steps, total_train_batches - window_start)
                (loss / window_size).backward()
                if (iter_num + 1) % accumulation_steps == 0 or (iter_num + 1) == total_train_batches:
                    optimizer.step()
            
            epoch_loss += loss.item()
                
        epoch_loss /= total_train_batches
        torch.cuda.empty_cache()
        epoch_end = time.time()
        current_lr = current_learning_rate(optimizer)
        logger.info("Epoch {} Rank {}: lr={:.6f}, loss={:.6f}, time={:.3f}".format(i, rank, current_lr, epoch_loss, epoch_end-epoch_start))
        
        lr_scheduler.step()
        del input, input_surface, target, target_surface, output, output_surface
        torch.cuda.empty_cache()

        if rank == 0:
            model_save_path = os.path.join(res_path, 'models')
            mkdir(model_save_path)
            if i % cfg.PG.TRAIN.SAVE_INTERVAL == 0:
                save_file = {"model": unwrap_model(model).state_dict(),
                             "optimizer": optimizer.state_dict(),
                             "lr_scheduler": lr_scheduler.state_dict(),
                             "epoch": i}
                torch.save(save_file, os.path.join(model_save_path, 'train_{}.pth'.format(i)))
                logger.info(f"model is saved at {i} epoch.")

            if i % cfg.PG.VAL.INTERVAL == 0:
                with torch.no_grad():
                    model.eval()
                    val_loss = 0.0
                    for val_data in tqdm(val_loader, desc='Validating'):
                        input_val, input_surface_val, target_val, target_surface_val, periods_val = val_data
                        input_val, input_surface_val, target_val, target_surface_val = input_val.to(device), input_surface_val.to(device), target_val.to(device), target_surface_val.to(device)

                        output_val, output_surface_val = model(input_val, input_surface_val,
                                                               aux_constants['weather_statistics'],
                                                               aux_constants['constant_maps'], aux_constants['const_h'])
                        target_val, target_surface_val = normData(target_val, target_surface_val, aux_constants['weather_statistics_last'])

                        # Get variables for validation too
                        vars_val = get_all_variables(output_surface_val, target_surface_val, output_val, target_val)

                        if only_use_wind_speed_loss:
                            if use_custom_mask:
                                surface_wind_speed_loss = masked_mean(criterion(vars_val['ws10'][0], vars_val['ws10'][1]), mask_float)
                                wind_speed_loss = masked_mean(criterion(vars_val['ws_upper'][0], vars_val['ws_upper'][1]), mask_float)
                                loss = surface_wind_speed_loss + wind_speed_loss
                            else:
                                loss = torch.mean(criterion(vars_val['ws10'][0], vars_val['ws10'][1])) + torch.mean(criterion(vars_val['ws_upper'][0], vars_val['ws_upper'][1]))
                        else:
                            val_loss_surface = criterion(output_surface_val, target_surface_val)
                            val_loss_upper = criterion(output_val, target_val)

                            if use_custom_mask:
                                weighted_val_loss_surface = masked_mean(val_loss_surface * surface_weights, mask_float)
                                weighted_val_loss_upper = masked_mean(val_loss_upper * upper_weights, mask_float)
                            else:
                                weighted_val_loss_surface = torch.mean(val_loss_surface * surface_weights)
                                weighted_val_loss_upper = torch.mean(val_loss_upper * upper_weights)
                            loss = weighted_val_loss_upper * upper_loss_weight + weighted_val_loss_surface * surface_loss_weight

                        val_loss += loss.item()

                    val_loss /= len(val_loader)
                    writer.add_scalars('Loss', {'train': epoch_loss, 'val': val_loss}, i)
                    logger.info("Validate at Epoch {} : {:.6f}".format(i, val_loss))

                    if visualize:
                        png_path = os.path.join(res_path, "png_training")
                        mkdir(png_path)
                        output_val, output_surface_val = normBackData(output_val, output_surface_val, aux_constants['weather_statistics_last'])
                        target_val, target_surface_val = normBackData(target_val, target_surface_val, aux_constants['weather_statistics_last'])
                        visuailze(output_val.detach().cpu().squeeze(), target_val.detach().cpu().squeeze(), input_val.detach().cpu().squeeze(), var='u', z=12, step=i, path=png_path)
                        visuailze_surface(output_surface_val.detach().cpu().squeeze(), target_surface_val.detach().cpu().squeeze(), input_surface_val.detach().cpu().squeeze(), var='msl', step=i, path=png_path)

                    if val_loss < best_loss:
                        best_loss = val_loss
                        torch.save(unwrap_model(model).state_dict(), os.path.join(model_save_path, 'best_model.pth'))
                        logger.info(f"current best model is saved at {i} epoch.")
                        epochs_since_last_improvement = 0
                    else:
                        epochs_since_last_improvement += 1
                        if epochs_since_last_improvement >= cfg.PG.TRAIN.EARLY_STOP:
                            logger.info(f"No improvement in validation loss for {epochs_since_last_improvement} epochs, terminating training.")
                            should_stop = True
                    del input_val, input_surface_val, target_val, target_surface_val, output_val, output_surface_val
                    torch.cuda.empty_cache()

        if is_dist_ready():
            stop_tensor = torch.tensor(1 if should_stop else 0, device=device)
            dist.broadcast(stop_tensor, src=0)
            should_stop = bool(stop_tensor.item())
        if should_stop:
            break

    return model

def str2bool(v):
    if isinstance(v, bool): return v
